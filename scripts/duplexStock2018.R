# duplexStock2018.R
# Stock of duplex buildings on the 2019 BCA roll (condition as of mid-2018), City of Vancouver,
# by 2018 zoning code. Building = roll-number stem floor(roll/1000), shared by strata folios on a lot.
# Writes text/duplexStock2018.tex
# Tom Davidoff 11/15/26

library(data.table)
library(RSQLite)

SQLITE_FILE <- "~/DropboxExternal/dataRaw/REVD19_and_inventory_extracts.sqlite3"
OUT_TEX     <- "../text/duplexStock2018.tex"
JUR         <- "200"
TOPK        <- 5

con <- dbConnect(SQLite(), path.expand(SQLITE_FILE))
fol <- as.data.table(dbGetQuery(con, "SELECT folioID, rollNumber, jurisdictionCode FROM folio"))
des <- as.data.table(dbGetQuery(con, "SELECT folioID, actualUseDescription FROM folioDescription"))
inv <- as.data.table(dbGetQuery(con, "SELECT roll_number, jurisdiction, zoning FROM residentialInventory"))
dbDisconnect(con)

for (d in list(fol, inv)) for (v in names(d)) set(d, j = v, value = trimws(d[[v]]))
fol <- fol[jurisdictionCode == JUR]
inv <- inv[jurisdiction == JUR]
stopifnot(!anyDuplicated(fol$folioID), !anyDuplicated(fol$rollNumber), !anyDuplicated(inv$roll_number))
stopifnot(!anyDuplicated(des$folioID))

n0 <- nrow(fol)
dt <- merge(fol, des, by = "folioID")
stopifnot(nrow(dt) <= n0)
cat(sprintf("folio -> description: %d of %d COV folios matched (lost %.2f%%)\n", nrow(dt), n0, 100 * (1 - nrow(dt) / n0)))

print(dt[grepl("duplex", actualUseDescription, ignore.case = TRUE), .N, by = actualUseDescription][order(-N)])
dup <- dt[grepl("^Duplex", actualUseDescription)]
nDupFolio <- nrow(dup)

dup <- merge(dup, inv[, .(rollNumber = roll_number, zoning)], by = "rollNumber", all.x = TRUE)
stopifnot(nrow(dup) == nDupFolio)
dup[zoning == "", zoning := NA_character_]
cat(sprintf("duplex folios without inventory zoning: %d of %d (%.2f%%)\n",
            dup[is.na(zoning), .N], nDupFolio, 100 * dup[is.na(zoning), .N] / nDupFolio))

dup[, rollStart := floor(as.numeric(rollNumber) / 1000)]
stopifnot(!anyNA(dup$rollStart))
dup[, strata := grepl("^Duplex, Strata", actualUseDescription)]
print(dup[, .(folios = .N, stems = uniqueN(rollStart)), by = actualUseDescription])
print(dup[, .N, by = .(rollStart, strata)][, .N, by = .(strata, foliosPerStem = N)][order(strata, foliosPerStem)])

# a stem may hold several unrelated buildings only if non-strata folios share it; check
mixed <- dup[, .(nNonStrata = sum(!strata), nStrata = sum(strata)), by = rollStart][nNonStrata > 1 | (nNonStrata > 0 & nStrata > 0)]
cat(sprintf("stems with >1 non-strata duplex folio or strata/non-strata mix: %d\n", nrow(mixed)))

zConflict <- dup[!is.na(zoning), uniqueN(zoning), by = rollStart][V1 > 1]
cat(sprintf("stems with conflicting zoning across folios: %d\n", nrow(zConflict)))

modeOrNA <- function(x) { x <- x[!is.na(x)]; if (!length(x)) NA_character_ else names(which.max(table(x))) }
bld <- dup[, .(zoning = modeOrNA(zoning),
               strata = any(strata), folios = .N), by = rollStart]
stopifnot(!anyDuplicated(bld$rollStart))
nBld <- nrow(bld)
cat(sprintf("duplex buildings (stems): %d; folios: %d; zoning missing: %d (%.2f%%)\n",
            nBld, nDupFolio, bld[is.na(zoning), .N], 100 * bld[is.na(zoning), .N] / nBld))

bz <- bld[!is.na(zoning), .N, by = zoning][order(-N)]
bz[, share := N / sum(N)]
bz[, family := fcase(grepl("^RS", zoning), "RS", grepl("^RT", zoning), "RT", grepl("^RM", zoning), "RM",
                     grepl("^CD", zoning), "CD", default = "other")]
print(bz[1:15])
print(bz[, .(N = sum(N), share = sum(share)), by = family][order(-N)])

nZoned    <- bz[, sum(N)]
nCodes    <- nrow(bz)
topShare  <- bz[1:TOPK, sum(N)] / nZoned
topCodes  <- paste(bz[1:TOPK, zoning], collapse = ", ")
rsShare   <- bz[family == "RS", sum(N)] / nZoned
rtShare   <- bz[family == "RT", sum(N)] / nZoned

fmtInt <- function(x) formatC(x, format = "d", big.mark = ",")
mac <- c(
  sprintf("\\newcommand{\\duplexBldgStockEighteen}{%s}", fmtInt(nBld)),
  sprintf("\\newcommand{\\duplexFolioStockEighteen}{%s}", fmtInt(nDupFolio)),
  sprintf("\\newcommand{\\duplexZoningCodesEighteen}{%d}", nCodes),
  sprintf("\\newcommand{\\duplexTopFiveZoneShareEighteen}{%.0f}", 100 * topShare),
  sprintf("\\newcommand{\\duplexTopFiveZonesEighteen}{%s}", topCodes),
  sprintf("\\newcommand{\\duplexRTShareEighteen}{%.0f}", 100 * rtShare),
  sprintf("\\newcommand{\\duplexRSShareEighteen}{%.0f}", 100 * rsShare)
)
writeLines(c("% generated by scripts/duplexStock2018.R; do not edit", mac), OUT_TEX)
cat(mac, sep = "\n")
