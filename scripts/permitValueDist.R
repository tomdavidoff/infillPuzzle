# permitValueDist.R
# Project value distribution of permits counted as new builds on 2018 R1-1 SFD lots, issued 2018+: New Building permits
# vs Addition / Alteration permits at or above the new-build value cutoff. Reads permitLotLinks.rds and
# permitNewBuildCutoffs.rds (run multiplexLotWidth.R first). otherMultiple dropped. Writes text/permitValueDist.tex.
# Tom Davidoff 11/23/26

library(data.table)

YEAR_MIN <- 2018
QS <- c(.1, .25, .5, .75, .9)
lost <- function(n0, n1, what) cat(sprintf("%-40s %6d -> %6d (lost %.1f%%)\n", what, n0, n1, 100 * (1 - n1 / n0)))

L  <- readRDS("~/DropboxExternal/dataProcessed/permitLotLinks.rds")
hv <- readRDS("~/DropboxExternal/dataProcessed/permitNewBuildCutoffs.rds")["A"]
n0 <- nrow(L); L <- L[newBuild == TRUE & product != "otherMultiple"]; lost(n0, nrow(L), "new build, principal product")
n0 <- nrow(L); L <- L[year(issued) >= YEAR_MIN]; lost(n0, nrow(L), "issued 2018+")
stopifnot(!anyDuplicated(L$permitnumber), L[typeofwork != "New Building", all(projectvalue >= hv)])
cat("zero or missing value:\n"); print(L[, .(N = .N, zeroNA = sum(is.na(projectvalue) | projectvalue <= 0)), by = .(typeofwork, product)])

L[, grp := factor(fifelse(typeofwork == "New Building", "New Building",
                          sprintf("Addition / Alteration, value $\\geq$ \\$%s", formatC(hv, format = "d", big.mark = ","))))]
L[, grp := relevel(grp, "New Building")]
d <- L[, c(.(N = .N), as.list(quantile(projectvalue, QS, na.rm = TRUE) / 1000)), keyby = grp]
print(d)
stopifnot(sum(d$N) == nrow(L))

row <- function(r) paste(c(as.character(r$grp), formatC(r$N, format = "d", big.mark = ","),
                           formatC(round(unlist(r[, -(1:2)])), format = "d", big.mark = ",")), collapse = " & ")
writeLines(c("% generated by scripts/permitValueDist.R; do not edit",
             "\\begin{tabular}{lrrrrrr}", "\\hline",
             sprintf("Type of work & N & %s \\\\", paste0("p", 100 * QS, collapse = " & ")), "\\hline",
             paste0(sapply(seq_len(nrow(d)), function(i) row(d[i])), " \\\\"),
             "\\hline", "\\end{tabular}"), "../text/permitValueDist.tex")
cat(readLines("../text/permitValueDist.tex"), sep = "\n")
