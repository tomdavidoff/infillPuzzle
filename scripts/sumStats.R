# sumStats.R
# Summary statistics (N, mean, SD, min, max) for the variables in the paper's tables, by unit of observation:
# SFD sales on 33-ft lots (ppsf, built elasticity), new-build sales (lot size elasticity), tracts and neighbourhoods
# (Tables 1, 2, 5), permits (Tables 5-8), and new-build FSR (replaces the old FSR table).
# Reads samples saved by vancouverPPSF33.R, lotElasticityNew.R, vancouverElasticityPremium.R, permitShareDiD.R,
# newBuildFSRPrePost.R. Writes text/sumStats.tex
# Tom Davidoff 11/21/26

library(data.table)
P <- "~/DropboxExternal/dataProcessed/"
MIN_DUP <- 10

sf <- readRDS(paste0(P, "ppsf33Sales.rds"))
ln <- readRDS(paste0(P, "lotElasNewSales.rds"))
S  <- readRDS(paste0(P, "shareDiDPermits.rds"))
fs <- readRDS(paste0(P, "newBuildFSR.rds"))[!is.na(per)]   # regression years only
eT <- fread(paste0(P, "elasPremiumTract.csv"), colClasses = list(character = "gid"))
lT <- fread(paste0(P, "lotElasNewTract_age14.csv"), colClasses = list(character = "gid"))[, .(gid, lotElas)]
stopifnot(!anyDuplicated(eT$gid), !anyDuplicated(lT$gid), !anyDuplicated(S$pT$CTUID), !anyDuplicated(S$pN$nbhd))

# tracts: the 56 with ppsf and built elasticity (permitShareDiD.R universe)
n0 <- nrow(S$pT); tr <- merge(S$pT, eT[, .(CTUID = gid, elas, dupPremium, nDUP, west, nSFD)], by = "CTUID", all.x = TRUE)
tr <- merge(tr, lT[, .(CTUID = gid, lotElas)], by = "CTUID", all.x = TRUE); stopifnot(nrow(tr) == n0, !anyNA(tr$elas))
stopifnot(all.equal(tr$ppsf, eT[match(tr$CTUID, gid), lppsf]))
tr[nDUP < MIN_DUP, dupPremium := NA]
# area ppsf FE are identified up to a constant (demeaned in the paper); report levels: shift so the sales-weighted
# mean equals mean log ppsf of the area's sales, i.e. predicted log ppsf at the sample's average sale year and vintage
eN <- fread(paste0(P, "elasPremiumNeighbourhood.csv"))[, .(nbhd = gid, lppsf, nSFD)]
nb <- merge(S$pN, eN, by = "nbhd"); stopifnot(nrow(nb) == nrow(S$pN), all.equal(nb$ppsf, nb$lppsf))
sT <- sf[CTUID %in% tr$CTUID]; sN <- sf[nbhd %in% nb$nbhd]
stopifnot(nrow(sT) == sum(tr$nSFD), nrow(sN) == sum(nb$nSFD))
kT <- mean(sT$lppsf) - weighted.mean(tr$ppsf, tr$nSFD); kN <- mean(sN$lppsf) - weighted.mean(nb$ppsf, nb$nSFD)
cat(sprintf("level shift: tract %.4f, nbhd %.4f\n", kT, kN))
tr[, lev := ppsf + kT]

# permits (permitShareDiD.R sample)
pm <- S$pm
pm <- merge(pm, S$pT[, .(CTUID, ppsfT = ppsf + kT)], by = "CTUID", all.x = TRUE)
pm <- merge(pm, S$pN[, .(nbhd, ppsfN = ppsf + kN)], by = "nbhd", all.x = TRUE); stopifnot(nrow(pm) == nrow(S$pm))

st <- function(x, lab, k = 2) { x <- x[!is.na(x)]
  sprintf("%s & %s & %s & %s & %s & %s \\\\", lab, formatC(length(x), format = "d", big.mark = ","),
          formatC(round(mean(x), k) + 0, format = "f", digits = k, big.mark = ","), formatC(sd(x), format = "f", digits = k, big.mark = ","),
          formatC(min(x), format = "f", digits = k, big.mark = ","), formatC(max(x), format = "f", digits = k, big.mark = ",")) }
# each panel gets \label{sumStats:<key>}; \ref prints the panel letter
panel <- function(title, key, ...) c("\\hline", sprintf("\\multicolumn{6}{l}{\\expandafter\\def\\csname @currentlabel\\endcsname{%s}\\label{sumStats:%s}\\textit{%s}} \\\\",
  substr(title, 1, 1), key, title), ...)

tab <- c("% generated by scripts/sumStats.R; do not edit",
  "\\begin{tabular}{lrrrrr}", "\\hline", "Variable & N & Mean & SD & Min & Max \\\\",
  panel("A. Single family sales, 33' lots now R1, 2012 to Sept. 2018", "sales33",
    st(sf$price / 1e3, "Price (\\$000)", 0), st(sf$sqft, "Finished floor area (sq. ft.)", 0),
    st(sf$price / sf$sqft, "Price per sq. ft. (\\$)", 0), st(sf$lppsf, "Log price per sq. ft."), st(sf$age, "Effective age (years)", 1)),
  panel("B. Single family sales, structure under 15 years old, lots now R1, same period", "salesNew",
    st(ln$price / 1e3, "Price (\\$000)", 0), st(exp(ln$llot), "Lot area (sq. ft.)", 0), st(ln$llot, "Log lot area"),
    st(ln$w, "Lot width (ft.)", 1), st(ln$age, "Age (years)", 1)),
  panel("C. Census tract derived statistics", "tract",
    st(tr$lev, "Log price per sq. ft."), st(exp(tr$lev), "Price per sq. ft. (\\$)", 0), st(tr$elas, "Built elasticity"), st(tr$lotElas, "Lot size elasticity"),
    st(tr$dupPremium, "Duplex premium"), st(as.numeric(tr$west), "West Side")),
  panel("D. New-build permits, 33' lots now R1, applied 2019--2022 and 2024--2026", "permits",
    st(pm$dup, "Duplex"), st(pm$post, "Post 2023 reform"), st(as.numeric(pm$side == "West"), "West Side"),
    st(pm$ppsfT, "Tract log price per sq. ft."), st(pm$ppsfN, "Neighbourhood log price per sq. ft.")),
  panel("E. Realized FSR of completed new builds", "fsr",
    st(fs[era == "duplexEra" & product == "single", fsr], "Single family, duplex era"), st(fs[era == "duplexEra" & product == "duplex", fsr], "Duplex, duplex era"),
    st(fs[era == "r1Era" & product == "single", fsr], "Single family, R1-1 era"), st(fs[era == "r1Era" & product == "duplex", fsr], "Duplex, R1-1 era")),
  "\\hline", "\\end{tabular}")
writeLines(tab, "../text/sumStats.tex"); cat(tab, sep = "\n")
