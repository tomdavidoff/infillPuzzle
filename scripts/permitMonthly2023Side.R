# permitMonthly2023Side.R
# Appendix table: 2023 new-build single and duplex permits on 33-ft lots now R1-1 (sample of permitShareDiD.R),
# by application month and side (West/East of Ontario St). October split at the R1-1 start (2023-10-17).
# Writes text/permitMonthly2023Side.tex
# Uses S$pmAll (anticipation window not dropped). Tom Davidoff 11/22/26

library(data.table)

S  <- readRDS("~/DropboxExternal/dataProcessed/shareDiDPermits.rds")   # from permitShareDiD.R
R1 <- as.IDate("2023-10-17")
d  <- S$pmAll[year(applied) == 2023]
cat(sprintf("2023 applications: %d of %d permits\n", nrow(d), nrow(S$pmAll)))
d[, mo := fifelse(month(applied) == 10, fifelse(applied < R1, 10.0, 10.5), as.numeric(month(applied)))]
lab <- c(setNames(month.name, 1:12)[-10], `10` = "October 1--16", `10.5` = "October 17--31")
tb <- dcast(d, mo ~ side + product, fun.aggregate = length, value.var = "dup")
tb <- merge(data.table(mo = c(1:9, 10, 10.5, 11, 12)), tb, by = "mo", all.x = TRUE)
for (k in setdiff(names(tb), "mo")) set(tb, which(is.na(tb[[k]])), k, 0L)
print(tb)
row <- function(lb, x) sprintf("%s & %d & %d & %s & %d & %d & %s \\\\", lb,
  x$West_single, x$West_duplex, shr(x$West_duplex, x$West_single), x$East_single, x$East_duplex, shr(x$East_duplex, x$East_single))
shr <- function(du, si) if (du + si == 0) "--" else sprintf("%.2f", du / (du + si))
body <- vapply(seq_len(nrow(tb)), function(i) row(lab[as.character(tb$mo[i])], tb[i]), "")
tot <- tb[, lapply(.SD, sum), .SDcols = -"mo"]
tab <- c("% generated by scripts/permitMonthly2023Side.R; do not edit",
  "\\begin{tabular}{lrrrrrr}", "\\hline",
  " & \\multicolumn{3}{c}{West Side} & \\multicolumn{3}{c}{East Side} \\\\",
  "Application month, 2023 & Single & Duplex & Duplex share & Single & Duplex & Duplex share \\\\", "\\hline",
  body[tb$mo <= 10], "\\hline", body[tb$mo > 10], "\\hline", row("Total", tot), "\\hline", "\\end{tabular}")
writeLines(tab, "../text/permitMonthly2023Side.tex"); cat(tab, sep = "\n")
