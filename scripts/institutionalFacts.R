# institutionalFacts.R
# Policy dates and zoning parameters for the institutional background, with source keys (text/CLAUDE.bib).
# Values transcribed from City of Vancouver by-laws and council reports; unit conversions computed here.
# Writes text/institutionalFacts.tex
# Tom Davidoff 11/15/26

library(data.table)

OUT_TEX <- "../text/institutionalFacts.tex"
M2FT    <- 3.28084

f <- fread(text = "
macro|value|source
suitesAllRSYear|2004|CoV2004Suites
suitesIllegalShareTwoThousandFour|78|CoV2004Suites
suitesTotalTwentyNineteen|34,593|CoV2019SuitesMemo
suitesPermittedShareTwentyNineteen|27|CoV2019SuitesMemo
lanewayFirstYear|2009|CoV2009Laneway
lanewayFirstLotShare|94|CoV2009Laneway
lanewayAllRSYear|2013|CoV2018LanewayReview
duplexCouncilMonth|September|CoV2018DuplexReport
duplexEnactedDate|October 30, 2018|CoV2018DuplexAdmin
rsDuplexFSR|0.70|CoVRS1Schedule2023
rsSingleBaseFSR|0.60|CoVRS1Schedule2023
rsSingleMaxFSR|0.70|CoVRS1Schedule2023
rOneCouncilMonth|September|CoV2023MissingMiddle
rOneEffectiveDate|October 17, 2023|CoV2023MissingMiddle
rOneSingleFSR|0.60|CoVR1Schedule
rOneDuplexFSR|0.70|CoVR1Schedule
rOneMultiplexBaseFSR|0.70|CoVR1Schedule
rOneMultiplexMaxFSR|1.00|CoVR1Schedule
rOneMultiplexRTYear|2024|vonBergmannMultiplex2025
rOneSixUnitMax|6|CoVR1Schedule
rOneRentalUnitMax|8|CoVR1Schedule
", sep = "|", colClasses = "character")

geo <- data.table(
  macro = c("rOneFourUnitFrontageM", "rOneFourUnitAreaM", "rOneSixUnitFrontageM", "rOneSixUnitAreaM"),
  m     = c(10.0, 306, 15.1, 557),
  pow   = c(1, 2, 1, 2))
geo[, ft := m * M2FT^pow]
depthFt <- geo[macro == "rOneFourUnitAreaM", m] / (33 / M2FT) * M2FT  # depth for 306 m2 on a 33-ft lot

stopifnot(!anyDuplicated(c(f$macro, geo$macro)), all(nzchar(f$source)))

mac <- c(
  f[, sprintf("\\newcommand{\\%s}{%s}", macro, value)],
  geo[, sprintf("\\newcommand{\\%s}{%s}", macro, fifelse(pow == 1, sprintf("%.1f", m), sprintf("%.0f", m)))],
  geo[, sprintf("\\newcommand{\\%s}{%s}", sub("M$", "Ft", macro), formatC(round(ft, if (pow[1] == 1) 1 else -1), format = "fg", big.mark = ",")), by = macro]$V1,
  sprintf("\\newcommand{\\rOneFourUnitDepthThirtyThreeFt}{%.0f}", depthFt)
)
writeLines(c("% generated by scripts/institutionalFacts.R; do not edit", mac), OUT_TEX)
cat(mac, sep = "\n")
