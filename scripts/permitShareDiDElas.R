webb <- c(-sqrt(1.5), -1, -sqrt(.5), sqrt(.5), 1, sqrt(1.5))
wcrBoot <- function(xs, var, d, B = NBOOT) {
  dm <- demean(as.matrix(d[, c("y", xs), with = FALSE]), d[, .(per)], weights = d$w)
  sw <- sqrt(d$w); y <- dm[, 1] * sw; X <- dm[, xs, drop = FALSE] * sw
  g  <- as.integer(factor(d$area)); k <- which(xs == var)
  tst <- function(Y) {
    XtXi <- solve(crossprod(X)); bet <- XtXi %*% crossprod(X, Y); E <- Y - X %*% bet
    v <- Reduce(`+`, lapply(seq_len(max(g)), function(h) (XtXi[k, ] %*% crossprod(X[g == h, , drop = FALSE], E[g == h, , drop = FALSE]))^2))
    bet[k, ] / sqrt(c(v))
  }
  t0 <- tst(matrix(y)); Xr <- X[, -k, drop = FALSE]
  u  <- if (ncol(Xr)) y - Xr %*% solve(crossprod(Xr), crossprod(Xr, y)) else y
  V  <- matrix(sample(webb, max(g) * B, replace = TRUE), max(g), B)
  mean(abs(tst(c(y - u) + V[g, , drop = FALSE] * c(u))) >= abs(t0))
}

n0 <- nrow(pm); d <- merge(pm[!is.na(CTUID)], ar, by = "CTUID")
cat(sprintf("permits with tract ppsf + elasticity: %d -> %d (lost %.1f%%)\n", n0, nrow(d), 100 * (1 - nrow(d) / n0)))
dc <- d[, .(y = mean(dup), w = .N, ppsf = ppsf[1], elas = elas[1], lot = lot[1]), by = .(area = CTUID, per, post)][
  , `:=`(postX = post * ppsf, postE = post * elas, postL = post * lot)][]

specs <- list(c("ppsf", "postX"), c("elas", "postE"), c("ppsf", "elas", "postX", "postE"), c("lot", "postL"), c("ppsf", "lot", "postX", "postL"))
res <- lapply(specs, function(xs) {
  dd <- dc[complete.cases(dc[, ..xs])]
  m <- feols(as.formula(paste("y ~", paste(xs, collapse = " + "), "| per")), dd, weights = ~w, cluster = ~area)
  stopifnot(nobs(m) == nrow(dd))
  list(m = m, d = dd, p = setNames(sapply(xs, wcrBoot, xs = xs, d = dd), xs))
})
m1L <- feols(y ~ ppsf + postX | per, dc[!is.na(lot)], weights = ~w, cluster = ~area)
cat("column 1 on the lot-elasticity tracts:\n"); print(coeftable(m1L))
for (r in res) { print(coeftable(r$m)); print(r$p) }

