cat(sprintf("tracts %d | sd ppsf %.3f | sd elas %.3f | cor %.3f | elas reliability (1 - mean se^2 / var) %.2f\n",
            nrow(a), sd(a$ppsf), sd(a$elas), cor(a$ppsf, a$elas), relE))
for (i in seq_along(res)) cat("spec", i, "1-sd effects:", round(coef(res[[i]]$m) * c(ppsf = sd(a$ppsf), postX = sd(a$ppsf), elas = sd(a$elas), postE = sd(a$elas), lot = sd(a$lot, na.rm = TRUE), postL = sd(a$lot, na.rm = TRUE))[names(coef(res[[i]]$m))], 3), "\n")

f3 <- function(x) sprintf("%.3f", x)
pv <- function(p) if (p < .001) "$<$0.001" else sprintf("%.3f", p)
stars <- function(p) if (p < .01) "^{***}" else if (p < .05) "^{**}" else if (p < .1) "^{*}" else ""
cellB <- function(r, v) if (v %in% names(coef(r$m))) sprintf("$%s%s$", f3(coef(r$m)[v]), stars(pvalue(r$m)[v])) else ""
cellS <- function(r, v) if (v %in% names(coef(r$m))) sprintf("(%s)", f3(se(r$m)[v])) else ""
cellP <- function(r, v) if (v %in% names(r$p)) pv(r$p[v]) else ""
row <- function(lab, x) paste(lab, "&", paste(x, collapse = " & "), "\\\\")
tab <- c("% generated by scripts/permitShareDiDElas.R; do not edit",
