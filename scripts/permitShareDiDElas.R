  row("\\quad wild bootstrap $p$", sapply(res, cellP, "postE")),
  row("Lot size elasticity", sapply(res, cellB, "lot")), row("", sapply(res, cellS, "lot")),
  row("\\quad wild bootstrap $p$", sapply(res, cellP, "lot")),
  row("Post 2023 $\\times$ lot size elasticity", sapply(res, cellB, "postL")), row("", sapply(res, cellS, "postL")),
  row("\\quad wild bootstrap $p$", sapply(res, cellP, "postL")),
  "\\hline",
